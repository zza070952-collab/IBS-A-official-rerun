#!/usr/bin/env python3
"""Configurable post-source-freeze ranking and separately reviewed nomination.

This source contains no gene exception or statistical threshold. A caller must
create the actual rule after all new source models/continuous evidence freeze.
--rank freezes every canonical row; --freeze-only never recomputes that ranking.
--validate-only performs contract/hash/header checks without ranking or writes.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sys
import time

PROJECT = "IBS_A_OFFICIAL_RERUN_20261105"
RESERVED_ID_COLUMNS = {"identity_key", "gene_symbol", "hgnc_id", "gene_id", "hgnc_entrez_id", "hgnc_ensembl_gene_id"}
OPERATIONS = {"min", "max", "mean", "median", "sum", "count_nonmissing", "count_positive", "fraction_positive"}


def arguments():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--root", required=True, type=Path)
    p.add_argument("--rule", required=True, help="Actual new-root caller-authored JSON; no rule is generated by this program")
    p.add_argument("--review", help="Separate source-cited human-model/siRNA/qPCR review JSON after full statistical ranking")
    p.add_argument("--source-freeze", default="results/integrated/continuous/INTEGRATION_SOURCE_FREEZE.json")
    p.add_argument("--out", default="results/integrated/statistical_ranking")
    p.add_argument("--freeze", default="results/integrated/CANDIDATE_FREEZE.json")
    modes = p.add_mutually_exclusive_group(required=True)
    modes.add_argument("--validate-only", action="store_true")
    modes.add_argument("--rank", action="store_true")
    modes.add_argument("--freeze-only", action="store_true")
    return p.parse_args()


def utc():
    return datetime.now(timezone.utc).isoformat()


def timestamp(text, label):
    t = datetime.fromisoformat(str(text).replace("Z", "+00:00"))
    if t.tzinfo is None:
        raise ValueError(f"{label} must include UTC offset/Z; no mtime substitute")
    return t


def need(obj, key, label):
    if key not in obj or obj[key] is None:
        raise ValueError(f"Missing explicit configuration {label}:{key}")
    return obj[key]


def digest(path):
    h = hashlib.sha256()
    with path.open("rb") as handle:
        for data in iter(lambda: handle.read(8 * 1024 * 1024), b""):
            h.update(data)
    return h.hexdigest()


def dump(path, obj):
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(obj, indent=2, ensure_ascii=False, allow_nan=False) + "\n", encoding="utf-8")
    temp.replace(path)


class NewInputs:
    def __init__(self, root):
        self.root, self.hashes = root, {}

    def path(self, name, exists=True):
        p = self.root / name
        if not p.resolve().is_relative_to(self.root) or p.is_symlink() or p.resolve() != p:
            raise ValueError(f"All paths must be real files in the new root: {p}")
        if exists and (not p.is_file() or not p.stat().st_size):
            raise FileNotFoundError(p)
        return p

    def register(self, name, expected=None):
        p = self.path(name)
        key = p.relative_to(self.root).as_posix()
        if key not in self.hashes:
            self.hashes[key] = digest(p)
        if expected is not None and self.hashes[key] != expected:
            raise ValueError(f"Frozen source SHA256 mismatch: {name}")
        return p

    def js(self, name):
        return json.loads(self.register(name).read_text(encoding="utf-8-sig"))

    def unchanged(self):
        for rel, expected in self.hashes.items():
            if digest(self.path(rel)) != expected:
                raise RuntimeError(f"Input changed during postprocessing: {rel}")


def criterion_contract(node, features):
    if not isinstance(node, dict):
        raise ValueError("A criterion must be a declarative JSON object")
    combinators = [key for key in ("all", "any") if key in node]
    if combinators:
        if len(combinators) != 1 or len(node) != 1:
            raise ValueError("Boolean criterion nodes contain exactly one all/any")
        key = combinators[0]
        children = node[key]
        if not isinstance(children, list) or not children:
            raise ValueError("Empty/non-list Boolean criterion would hide a rule")
        for child in children:
            criterion_contract(child, features)
        return
    if set(node) - {"feature", "op", "value", "missing"}:
        raise ValueError("Unknown criterion field; arbitrary expressions are forbidden")
    if need(node, "feature", "criterion") not in features:
        raise ValueError("Criterion refers to an undeclared feature")
    op = need(node, "op", "criterion")
    if op not in {"lt", "le", "gt", "ge", "eq", "ne", "in", "not_in", "is_missing", "not_missing", "is_true"}:
        raise ValueError("Unsupported declarative criterion operator")
    if need(node, "missing", "criterion") not in {"unknown", "false", "error"}:
        raise ValueError("Missing evidence cannot silently become positive: use unknown, false or error")
    if op not in {"is_missing", "not_missing", "is_true"}:
        need(node, "value", "criterion")


def evaluate(node, features):
    import pandas as pd
    if "all" in node or "any" in node:
        key = "all" if "all" in node else "any"
        values = [evaluate(child, features) for child in node[key]]
        result = values[0]
        for value in values[1:]:
            result = result & value if key == "all" else result | value
        return result
    x, op = features[node["feature"]], node["op"]
    missing = x.isna()
    if op == "is_missing":
        return missing.astype("boolean")
    if op == "not_missing":
        return (~missing).astype("boolean")
    if op == "is_true":
        result = x.eq(True)
    elif op == "in":
        result = x.isin(node["value"])
    elif op == "not_in":
        result = ~x.isin(node["value"])
    else:
        result = {"lt": x.lt, "le": x.le, "gt": x.gt, "ge": x.ge, "eq": x.eq, "ne": x.ne}[op](node["value"])
    result = result.astype("boolean")
    if missing.any():
        if node["missing"] == "error":
            raise ValueError("Configured criterion has missing evidence and missing=error")
        result.loc[missing] = False if node["missing"] == "false" else pd.NA
    return result


def validate_rule(rule, source, source_hash, gate, header):
    if rule.get("schema_version") != 1 or rule.get("same_rule_for_every_gene") is not True or rule.get("gene_specific_exceptions") is not False:
        raise ValueError("Rule must certify schema1, same rule for all genes and no gene-specific exception")
    if need(rule, "source_freeze_sha256", "rule") != source_hash:
        raise ValueError("Rule was not bound to this exact frozen source catalogue")
    source_time = timestamp(need(source, "frozen_at", "source freeze"), "source freeze")
    created = timestamp(need(rule, "created_at", "rule"), "rule created_at")
    if not source_time <= created <= datetime.now(timezone.utc):
        raise ValueError("Rule creation must occur after source freeze and cannot be future-dated")
    if need(rule, "wide_table", "rule") != gate["wide_table"] or need(rule, "wide_table_sha256", "rule") != gate["wide_table_sha256"]:
        raise ValueError("Rule does not bind the complete newly frozen wide table")
    columns = need(rule, "columns", "rule")
    if not isinstance(columns, dict) or not columns:
        raise ValueError("Explicit evidence-column mappings are required")
    features = set()
    for alias, spec in columns.items():
        if not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", alias) or alias in {"evidence_grade", "selection_eligible", "statistical_rank"}:
            raise ValueError("Feature aliases must be simple names")
        source_column = need(spec, "source", "column mapping")
        if source_column not in header or source_column in RESERVED_ID_COLUMNS:
            raise ValueError("Unknown/identity column cannot be a ranking criterion")
        if need(spec, "kind", "column mapping") not in {"numeric", "boolean", "category"}:
            raise ValueError("Every mapped column needs an explicit numeric/boolean/category kind")
        need(spec, "description", "column mapping")
        if not isinstance(need(spec, "missing_tokens", "column mapping"), list):
            raise ValueError("Every column mapping explicitly declares any native missing-string tokens, or []")
        features.add(alias)
    for spec in need(rule, "derived_features", "rule"):
        name = need(spec, "name", "derived feature")
        if name in features or name in {"evidence_grade", "selection_eligible", "statistical_rank"} or not re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name):
            raise ValueError("Duplicate/invalid derived feature name")
        if re.search(r"(combined|pooled|omnibus|meta)_?p(?:value)?", name, re.I):
            raise ValueError("A descriptive min/max across P/FDR columns is not a combined/meta/pooled inferential P")
        if need(spec, "role", "derived feature") != "descriptive_summary" or spec.get("inferential") is not False:
            raise ValueError("Derived aggregates must be explicitly descriptive and noninferential")
        if need(spec, "op", "derived feature") not in OPERATIONS:
            raise ValueError("Unsupported derived operation; this program performs no P-value combination")
        inputs = need(spec, "inputs", "derived feature")
        if not inputs or len(inputs) != len(set(inputs)) or not set(inputs).issubset(features):
            raise ValueError("Derived inputs must be declared before their use")
        if need(spec, "missing", "derived feature") not in {"skip", "propagate", "error"}:
            raise ValueError("Derived missing policy must be explicit")
        minimum = need(spec, "min_nonmissing", "derived feature")
        if not isinstance(minimum, int) or not 1 <= minimum <= len(inputs):
            raise ValueError("Derived aggregate requires an explicit positive minimum observed-input count")
        need(spec, "description", "derived feature"); need(spec, "unit", "derived feature")
        features.add(name)
    criterion_contract(need(rule, "eligibility", "rule"), features)
    grades = need(rule, "grades", "rule")
    if rule.get("grade_match_policy") != "first_matching_in_declared_order":
        raise ValueError("Grade matching policy must be explicit")
    grade_names = []
    for grade in grades:
        grade_names.append(need(grade, "label", "grade"))
        criterion_contract(need(grade, "criterion", "grade"), features)
    default = need(rule, "default_grade", "rule")
    all_grades = grade_names + [default]
    if len(set(all_grades)) != len(all_grades) or set(need(rule, "grade_order", "rule")) != set(all_grades) or len(rule["grade_order"]) != len(all_grades):
        raise ValueError("Grade labels/default/order must be unique and complete")
    order = need(rule, "order", "rule")
    if not isinstance(order, list) or not order:
        raise ValueError("Explicit complete statistical ordering is required")
    for key in order:
        if need(key, "feature", "sort key") not in features | {"evidence_grade", "selection_eligible"}:
            raise ValueError("Unknown statistical sort feature")
        if need(key, "direction", "sort key") not in {"ascending", "descending"} or need(key, "missing", "sort key") not in {"first", "last", "error"}:
            raise ValueError("Sort direction/missing placement must be explicit")
    if len({key["feature"] for key in order}) != len(order):
        raise ValueError("Duplicate statistical sort key is not an explicit reproducible ordering")
    if not isinstance(need(rule, "measurement_status_legend", "rule"), dict):
        raise ValueError("Figure status legend must be supplied, not guessed")
    need(rule, "interpretation_boundary", "rule")


def feature_matrix(frame, rule):
    import numpy as np
    import pandas as pd
    features = {}
    for alias, spec in rule["columns"].items():
        raw = frame[spec["source"]].mask(frame[spec["source"]].astype("string").isin(spec["missing_tokens"]))
        if spec["kind"] == "numeric":
            value = pd.to_numeric(raw, errors="coerce")
            bad = raw.notna() & raw.astype(str).ne("") & value.isna()
            if bad.any() or np.isinf(value).any():
                raise ValueError("Non-numeric/nonfinite value in explicitly numeric ranking column: " + alias)
        elif spec["kind"] == "boolean":
            text = raw.astype("string").str.lower()
            if (~text.isin(["true", "false", "1", "0"]) & text.notna()).any():
                raise ValueError("Unknown boolean source value: " + alias)
            value = text.map({"true": True, "false": False, "1": True, "0": False}).astype("boolean")
        else:
            value = raw.astype("string")
        features[alias] = value
    for spec in rule["derived_features"]:
        values = pd.concat([pd.to_numeric(features[name], errors="raise") for name in spec["inputs"]], axis=1)
        valid_n = values.notna().sum(axis=1)
        if spec["missing"] == "error" and values.isna().any().any():
            raise ValueError("Missing derived input with missing=error")
        op = spec["op"]
        if op in {"min", "max", "mean", "median", "sum"}:
            v = getattr(values, op)(axis=1, skipna=True)
        elif op == "count_nonmissing":
            v = valid_n.astype(float)
        elif op == "count_positive":
            v = (values > 0).sum(axis=1).astype(float)
        else:
            v = (values > 0).sum(axis=1) / valid_n.replace(0, np.nan)
        insufficient = valid_n < spec["min_nonmissing"]
        if spec["missing"] == "propagate":
            insufficient |= values.isna().any(axis=1)
        features[spec["name"]] = v.astype(float).mask(insufficient)
    return features


def validate_review(review, ranking_freeze, ranking, d):
    if review.get("schema_version") != 1 or review.get("experimental_data_generated") is not False:
        raise ValueError("Feasibility review must be schema1 and must not assert generated experiments")
    reviewed = timestamp(need(review, "created_at", "review"), "review created_at")
    if not timestamp(ranking_freeze["frozen_at"], "ranking freeze") <= reviewed <= datetime.now(timezone.utc):
        raise ValueError("Feasibility review must follow the actual completed statistical ranking")
    for key in ("ranking_table_sha256", "ranking_rule_sha256"):
        if need(review, key, "review") != ranking_freeze[key]:
            raise ValueError("Review refers to a different frozen statistical ranking/rule")
    sources = {}
    for item in need(review, "evidence_sources", "review"):
        identifier = need(item, "id", "review source")
        if identifier in sources:
            raise ValueError("Duplicate feasibility-source ID")
        d.register(need(item, "path", "review source"), need(item, "sha256", "review source"))
        need(item, "description", "review source")
        urls = need(item, "urls", "review source")
        if not isinstance(urls, list) or not urls or not all(isinstance(u, str) and u.startswith("https://") for u in urls):
            raise ValueError("Feasibility sources require actual source-citation URLs and a hashed new-root audit file")
        sources[identifier] = item
    main = review.get("main_target")
    backups = need(review, "backup_targets", "review")
    if not isinstance(backups, list) or len(backups) > 2:
        raise ValueError("At most two reviewed backups are permitted")
    if main is None:
        if backups or not need(review, "no_target_reason", "review"):
            raise ValueError("No-target freeze requires a reason and no backup promotion")
        return [], sources
    targets = [main] + backups
    if len({t["identity_key"] for t in targets}) != len(targets):
        raise ValueError("Duplicate reviewed target identity")
    indexed = ranking.set_index("identity_key", drop=False)
    def cited(claim, label):
        need(claim, "statement", label)
        references = need(claim, "source_ids", label)
        if not references or not set(references).issubset(sources):
            raise ValueError("Feasibility claim lacks declared source evidence: " + label)
    output = []
    for target in targets:
        key = need(target, "identity_key", "reviewed target")
        if key not in indexed.index or str(indexed.loc[key, "selection_eligible"]).lower() not in ("true", "1"):
            raise ValueError("Reviewed target is absent or fails the uniformly frozen eligibility rule")
        need(target, "selection_reason", "reviewed target")
        spatial_symbols = need(target, "spatial_symbols", "reviewed target")
        if not isinstance(spatial_symbols, list) or not all(isinstance(s, str) and s for s in spatial_symbols):
            raise ValueError("spatial_symbols must explicitly list verified raw symbols or be empty")
        feasibility = need(target, "feasibility", "reviewed target")
        for field in ("human_model", "target_expression", "sirna_availability", "IBS_or_visceral_sensitivity_rationale"):
            cited(need(feasibility, field, "feasibility"), field)
        endpoints = need(feasibility, "qpcr_downstream", "feasibility")
        if not isinstance(endpoints, list) or not 2 <= len(endpoints) <= 4:
            raise ValueError("The user requires two to four source-cited proposed qPCR downstream transcripts")
        endpoint_symbols = [need(endpoint, "gene_symbol", "proposed qPCR endpoint") for endpoint in endpoints]
        if len(set(endpoint_symbols)) != len(endpoint_symbols) or indexed.loc[key, "gene_symbol"] in endpoint_symbols:
            raise ValueError("Downstream endpoints must be distinct transcripts, not duplicated rows or the knockdown target itself")
        for endpoint in endpoints:
            need(endpoint, "gene_symbol", "proposed qPCR endpoint")
            cited(endpoint, "proposed qPCR endpoint")
            if need(endpoint, "direction", "proposed qPCR endpoint") not in {"increase_expected", "decrease_expected", "uncertain", "context_dependent"}:
                raise ValueError("qPCR direction must explicitly admit uncertainty/context dependence")
        row = indexed.loc[key]
        output.append({"identity_key": key, "gene_symbol": row.gene_symbol, "spatial_symbols": spatial_symbols,
                       "statistical_rank": int(row.statistical_rank), "evidence_grade": row.evidence_grade,
                       "selection_reason": target["selection_reason"], "feasibility": feasibility})
    # Verify caller-supplied raw symbols against this run's approved identity
    # mapping. No candidate name is inferred from a previously ranked project.
    import pandas as pd
    verified = {t["identity_key"]: set() for t in output}
    mapping = d.register("results/integrated/continuous/FEATURE_IDENTITY_MAP.tsv.gz")
    for chunk in pd.read_csv(mapping, sep="\t", chunksize=100000, dtype=str, keep_default_na=False):
        hit = chunk.loc[chunk.identity_key.isin(verified) & chunk.module.str.startswith("SPATIAL")]
        for key, group in hit.groupby("identity_key", sort=False):
            verified[key].update(group.provided_symbol)
    for target in output:
        if not set(target["spatial_symbols"]).issubset(verified[target["identity_key"]]):
            raise ValueError("A proposed plotting symbol was not uniquely mapped to this fresh target in the new spatial data")
    return output, sources


def main():
    args = arguments()
    root = args.root.resolve()
    if root.name != PROJECT:
        raise ValueError("Only the authorised new project is accepted")
    import numpy as np
    import pandas as pd
    d = NewInputs(root)
    start, tick = utc(), time.monotonic()
    for gate_name in ("PHASE0_GATE", "PHASE1_GATE", "SOFTWARE_GATE", "GWAS_MAGMA_GATE", "BULK_GATE", "BAYESSPACE_GATE", "SPATIALDM_GATE", "INTEGRATION_CONTINUOUS_GATE"):
        gate = d.js(f"manifest/{gate_name}.json")
        if gate.get("status") != "PASS":
            raise RuntimeError("All new source modules must finish before ranking: " + gate_name)
    continuous_gate = d.js("manifest/INTEGRATION_CONTINUOUS_GATE.json")
    source = d.js(args.source_freeze)
    source_file = d.register(args.source_freeze, continuous_gate["source_freeze_sha256"])
    if source.get("status") != "FROZEN" or source.get("ranking_performed") is not False:
        raise ValueError("Expected a frozen unranked continuous source catalogue")
    for rel, item in need(source, "source_files", "source freeze").items():
        d.register(rel, item["sha256"])
    wide_file = d.register(continuous_gate["wide_table"], continuous_gate["wide_table_sha256"])
    evidence_file = d.register(continuous_gate["evidence_file"], continuous_gate["evidence_sha256"])
    rule = d.js(args.rule)
    rule_rel = d.path(args.rule).relative_to(root).as_posix()
    rule_hash = d.hashes[rule_rel]
    source_hash = continuous_gate["source_freeze_sha256"]
    header = list(pd.read_csv(wide_file, sep="\t", nrows=0).columns)
    validate_rule(rule, source, digest(source_file), continuous_gate, header)
    out = d.path(args.out, exists=False)
    if not out.is_relative_to(root / "results/integrated"):
        raise ValueError("Ranking outputs must remain in the new integrated-results directory")
    rank_path, rank_freeze_path = out / "STATISTICAL_RANKING_ALL_GENES.tsv.gz", out / "STATISTICAL_RANKING_FREEZE.json"
    candidate_path = d.path(args.freeze, exists=False)
    if not candidate_path.is_relative_to(root / "results/integrated"):
        raise ValueError("Candidate decision must remain inside this new integrated-results directory")
    if args.validate_only and not args.review:
        d.unchanged()
        print(json.dumps({"status": "VALIDATED_NO_RANKING_OR_OUTPUT", "source_freeze_sha256": digest(source_file), "rule_sha256": digest(d.path(args.rule)), "explicit_features": list(rule["columns"])})); return
    if args.rank:
        if args.review:
            raise ValueError("Feasibility review follows completed ranking; do not combine selection with --rank")
        if candidate_path.exists() or (out.exists() and any(out.iterdir())):
            raise FileExistsError("Ranking/decision attempt already exists; preserve it, never silently overwrite/re-rank")
        table = pd.read_csv(wide_file, sep="\t", dtype=str, keep_default_na=False, low_memory=False)
        if table.empty or not {"identity_key", "gene_symbol"}.issubset(table) or table.identity_key.duplicated().any():
            raise ValueError("Ranking requires every canonical identity exactly once")
        if {"statistical_rank", "selection_eligible", "evidence_grade", "__rank_sort_temp__"}.intersection(table):
            raise ValueError("Input is already ranked or contains reserved ranking output columns")
        features = feature_matrix(table, rule)
        eligible = evaluate(rule["eligibility"], features)
        table["selection_eligibility_unknown"] = eligible.isna()
        table["selection_eligible"] = eligible.fillna(False).astype(bool)
        grades = pd.Series(rule["default_grade"], index=table.index, dtype="string")
        assigned = pd.Series(False, index=table.index)
        grade_audit = {}
        for grade in rule["grades"]:
            matched = evaluate(grade["criterion"], features)
            grade_audit[grade["label"]] = {"matching_true_rows": int(matched.fillna(False).sum()), "unknown_rows": int(matched.isna().sum())}
            choose = ~assigned & matched.fillna(False)
            grades.loc[choose], assigned.loc[choose] = grade["label"], True
        table["evidence_grade"] = grades
        for alias, values in features.items():
            name = "configured_feature__" + alias
            if name in table:
                raise ValueError("Configured feature would overwrite an original source statistic")
            table[name] = values
        sort_features = {**features, "selection_eligible": table.selection_eligible,
                         "evidence_grade": grades.map({g: i for i, g in enumerate(rule["grade_order"])})}
        ranked = table.sort_values("identity_key", kind="mergesort")
        for order in reversed(rule["order"]):
            name = "__rank_sort_temp__"
            ranked[name] = sort_features[order["feature"]].reindex(ranked.index)
            if order["missing"] == "error" and ranked[name].isna().any():
                raise ValueError("Missing sort value with configured missing=error")
            ranked = ranked.sort_values(name, ascending=order["direction"] == "ascending",
                                        na_position="last" if order["missing"] == "error" else order["missing"], kind="mergesort").drop(columns=name)
        ranked.insert(0, "statistical_rank", np.arange(1, len(ranked) + 1))
        d.unchanged()
        out.mkdir(parents=True)
        ranked.to_csv(rank_path, sep="\t", index=False, compression="gzip", na_rep="NA", float_format="%.17g")
        d.unchanged()
        record = {"status": "FROZEN", "frozen_at": utc(), "start_iso8601": start, "duration_seconds": time.monotonic() - tick,
                  "all_canonical_rows_retained": len(ranked), "candidate_selection_performed": False,
                  "ranking_rule_file": rule_rel, "ranking_rule_sha256": rule_hash,
                  "ranking_rule_frozen_at": rule["created_at"], "source_freeze_file": source_file.relative_to(root).as_posix(),
                  "source_freeze_sha256": source_hash, "wide_table": wide_file.relative_to(root).as_posix(), "wide_table_sha256": continuous_gate["wide_table_sha256"],
                  "ranking_table": rank_path.relative_to(root).as_posix(), "ranking_table_sha256": digest(rank_path),
                  "grade_audit": grade_audit, "grade_counts": ranked.evidence_grade.value_counts().to_dict(),
                  "derived_feature_definitions": rule["derived_features"], "input_sha256": d.hashes,
                  "tie_breaker": "identity_key lexicographic only after every configured statistical sort key",
                  "interpretation_boundary": rule["interpretation_boundary"], "no_new_inferential_P_test": True}
        dump(rank_freeze_path, record)
        print(json.dumps({"status": "STATISTICAL_RANKING_FROZEN_NO_TARGET_SELECTED", "rows": len(ranked), "ranking_freeze": str(rank_freeze_path)})); return
    if not args.review:
        raise ValueError("--freeze-only requires a separately authored post-ranking --review")
    if candidate_path.exists() and not args.validate_only:
        raise FileExistsError("Candidate freeze already exists; no silent overwrite or target rescue")
    ranking_freeze = d.js(str(rank_freeze_path.relative_to(root)))
    if ranking_freeze.get("status") != "FROZEN" or ranking_freeze["ranking_rule_sha256"] != rule_hash or ranking_freeze["source_freeze_sha256"] != source_hash:
        raise ValueError("Frozen statistical ranking is not bound to the current immutable rule/source")
    rank_file = d.register(str(rank_path.relative_to(root)), ranking_freeze["ranking_table_sha256"])
    ranking = pd.read_csv(rank_file, sep="\t", low_memory=False)
    review = d.js(args.review)
    selected, review_sources = validate_review(review, ranking_freeze, ranking, d)
